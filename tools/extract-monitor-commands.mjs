#!/usr/bin/env node
// Extract the Monitor command list from Renode's own sources, so the
// completion and hover descriptions are the ones Renode itself prints rather
// than something written from memory.
//
//   git clone --depth 1 --filter=blob:none --sparse \
//     https://github.com/renode/renode-infrastructure /tmp/infra
//   git -C /tmp/infra sparse-checkout set src/Emulator/Extensions/UserInterface
//   node tools/extract-monitor-commands.mjs /tmp/infra
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const infra = process.argv[2];
if (!infra) {
  console.error('usage: node tools/extract-monitor-commands.mjs <renode-infrastructure checkout>');
  process.exit(2);
}

const dir = path.join(infra, 'src/Emulator/Extensions/UserInterface/Commands');
if (!fs.existsSync(dir)) {
  console.error(`not a renode-infrastructure checkout: ${dir} is missing`);
  process.exit(2);
}

// Command classes call: base(monitor, "name", "description", "alias", ...)
const SIGNATURE = /:\s*base\s*\(\s*monitor\s*,\s*((?:"(?:[^"\\]|\\.)*"\s*,?\s*)+)\)/;

const unquote = (s) => s.slice(1, -1).replace(/\\(.)/g, '$1');

// A few classes pass a const instead of a literal: base(monitor, Command, "...").
const CONST_SIGNATURE =
  /:\s*base\s*\(\s*monitor\s*,\s*([A-Za-z_]\w*)\s*,\s*((?:"(?:[^"\\]|\\.)*"\s*,?\s*)+)\)/;

const commands = [];
for (const file of fs.readdirSync(dir).filter((f) => f.endsWith('.cs')).sort()) {
  const text = fs.readFileSync(path.join(dir, file), 'utf8');
  const rel = `renode-infrastructure/${path.relative(infra, path.join(dir, file))}`;

  let name;
  let rest;
  const literal = text.match(SIGNATURE);
  if (literal) {
    rest = literal[1];
  } else {
    const viaConst = text.match(CONST_SIGNATURE);
    if (!viaConst) continue;
    const decl = text.match(
      new RegExp(`const\\s+string\\s+${viaConst[1]}\\s*=\\s*"((?:[^"\\\\]|\\\\.)*)"`)
    );
    if (!decl) continue; // parameterised name, resolved from Monitor.cs below
    name = decl[1];
    rest = viaConst[2];
  }

  const parts = rest.match(/"(?:[^"\\]|\\.)*"/g)?.map(unquote) ?? [];
  if (!parts.length) continue;
  const [description, ...aliases] = name ? parts : parts.slice(1);
  if (!name) name = parts[0];
  if (!name || /\s/.test(name) || !description) continue;
  commands.push({ name, aliases: aliases.filter(Boolean), description, source: rel });
}

// SetCommand and ExecuteCommand are generic; their concrete names and the noun
// filled into their description template live in Monitor.cs.
const monitorFile = path.join(infra, 'src/Emulator/Extensions/UserInterface/Monitor.cs');
if (fs.existsSync(monitorFile)) {
  const monitor = fs.readFileSync(monitorFile, 'utf8');
  const templates = {
    SetCommand: 'sets {0}.',
    ExecuteCommand: 'executes a command or the content of a {0}.'
  };
  for (const [cls, template] of Object.entries(templates)) {
    const re = new RegExp(`new ${cls}\\(this,\\s*"([^"]*)",\\s*"([^"]*)"`, 'g');
    for (const m of monitor.matchAll(re)) {
      if (commands.some((c) => c.name === m[1])) continue;
      commands.push({
        name: m[1],
        aliases: [],
        description: template.replace('{0}', m[2]),
        source: `renode-infrastructure/${path.relative(infra, monitorFile)}`
      });
    }
  }
}

commands.sort((a, b) => a.name.localeCompare(b.name));
const out = path.join(root, 'data/monitor-commands.json');
fs.writeFileSync(
  out,
  JSON.stringify(
    {
      $comment:
        'Generated by tools/extract-monitor-commands.mjs from renode-infrastructure. Do not edit by hand.',
      commands
    },
    null,
    2
  ) + '\n'
);
console.log(`wrote ${path.relative(root, out)}: ${commands.length} commands`);
for (const c of commands.slice(0, 5)) console.log(`  ${c.name} - ${c.description}`);
